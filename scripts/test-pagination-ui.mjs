import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1920,height:1080}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const blocks=Array.from({length:35},(_,i)=>({type:'paragraph',text:'第'+i+'段：'+ '这是用于检查双屏分页的文字，调整窗口和字号后应保持完整，左右页按顺序继续阅读。'.repeat(18)}));
 blocks.splice(5,0,{type:'image',caption:'分页配图',src:'data:image/svg+xml,'+encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="800" height="1400"><rect width="800" height="1400" fill="#aac4b3"/></svg>')});
 await page.route('**/api/read?*',r=>r.fulfill({json:{result:{title:'双屏阅读排版检查',meta:'仅用于界面验证',access:'unverified',url:'https://www.cbnweek.com/article_detail/34768',blocks}}}));
 await page.goto('http://127.0.0.1:4317/?provider=cbnweek&issue='+encodeURIComponent('https://www.cbnweek.com/magalog/649')+'#article/'+encodeURIComponent('https://www.cbnweek.com/article_detail/34768'));
 await page.locator('.paper').waitFor();
 await page.selectOption('#reading-mode','spread');await page.locator('.page-controls').waitFor();
 await page.waitForTimeout(150);
 assert.equal(await page.locator('#previous-page').isDisabled(),true);
 assert.equal(await page.locator('#next-page').isDisabled(),false);
 await page.locator('#next-page').click();assert.match(await page.locator('#page-position').innerText(),/^2 /);
 await page.keyboard.press('PageDown');assert.match(await page.locator('#page-position').innerText(),/^3 /);
 await page.keyboard.press('PageUp');assert.match(await page.locator('#page-position').innerText(),/^2 /);
 assert.equal(await page.locator('#article-body p').count(),35);
 await page.click('.reader-settings summary');await page.click('#larger');await page.waitForTimeout(100);
 assert.equal(await page.locator('#article-body').evaluate(e=>getComputedStyle(e).fontSize),'22px');
 await page.click('.reader-settings summary');
 await page.selectOption('#theme','dark');await page.waitForTimeout(100);
 await page.locator('#theme').focus();
 const position=await page.locator('#page-position').innerText();
 await page.keyboard.press('PageDown');assert.equal(await page.locator('#page-position').innerText(),position,'select retains keyboard behavior');
 await page.evaluate(()=>document.querySelector('#account').showModal());
 await page.keyboard.press('PageDown');assert.equal(await page.locator('#page-position').innerText(),position,'modal suppresses pagination');
 await page.evaluate(()=>document.querySelector('#account').close());
 await page.selectOption('#theme','white');
 await page.click('#wide-reading');await page.waitForTimeout(100);
 await page.screenshot({path:'/tmp/reader-spread.png'});
 await page.locator('#next-page').evaluate(e=>{while(!e.disabled)e.click()});
 assert.equal(await page.locator('#next-page').isDisabled(),true);
 const last=await page.locator('.reading-end').evaluate(el=>{const rs=[...el.getClientRects()],v=document.querySelector('#spread-viewport').getBoundingClientRect();return rs.some(r=>r.left>=v.left-1&&r.right<=v.right+1)});
 assert.equal(last,true,'End of article reachable');
 await page.selectOption('#reading-mode','single');await page.waitForTimeout(100);
 assert.equal(await page.locator('.page-controls').isVisible(),false);
 await page.evaluate(()=>scrollTo(0,600));assert.ok((await page.locator('.reader-dock').boundingBox()).y<0,'toolbar scrolls');
 await page.selectOption('#reading-mode','columns');assert.equal(await page.locator('#article-body').evaluate(e=>getComputedStyle(e).columnCount),'2');
 await page.setViewportSize({width:390,height:844});await page.selectOption('#reading-mode','spread');await page.waitForTimeout(150);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.equal(await page.locator('#spread-flow').evaluate(e=>getComputedStyle(e).columnCount),'1');
 await page.locator('.shelf-return').click();await page.waitForFunction(()=>!document.body.classList.contains('reading'));
 assert.deepEqual(errors,[]);
 console.log('PASS: three modes, two-page pagination, keys, boundaries, last paragraph, image, wide layout, mobile, shelf, scrolling toolbar');
}finally{await browser.close()}
